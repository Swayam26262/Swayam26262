"""Every generated SVG must be well-formed, keep ids unique and only reference ids it defines."""

import re
import sys
import unittest
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import build  # noqa: E402
from core.theme import THEMES  # noqa: E402

REF = re.compile(r'url\(#([^)]+)\)|href="#([^"]+)"')


def check(test: unittest.TestCase, name: str, svg: str) -> None:
    root = ET.fromstring(svg)  # raises on malformed XML
    ids = [el.get("id") for el in root.iter() if el.get("id")]
    test.assertEqual(len(ids), len(set(ids)), f"{name}: duplicate ids")
    targets = {el.get("id"): el.tag.split("}")[-1] for el in root.iter() if el.get("id")}
    for a, b in REF.findall(svg):
        ref = a or b
        test.assertIn(ref, targets, f"{name}: dangling reference #{ref}")
        test.assertNotIn(targets[ref], ("title", "desc"), f"{name}: #{ref} points at <{targets[ref]}>")


class SvgTest(unittest.TestCase):
    def test_cards_render_cleanly(self):
        profile = build.load_profile()
        sample = {}  # no live data: cards must still render (placeholders)
        for name, render in build.CARDS.items():
            for theme in THEMES:
                result = render(profile, theme, sample, None)
                outputs = result if isinstance(result, dict) else {name: result}
                for stem, svg in outputs.items():
                    with self.subTest(f"{stem}-{theme.name}"):
                        check(self, stem, svg)

    def test_committed_assets(self):
        assets = Path(build.ASSETS)
        for path in sorted(assets.rglob("*.svg")):
            if path.name.startswith("snake-"):
                continue  # generated by Platane/snk
            with self.subTest(path.name):
                check(self, path.name, path.read_text())


if __name__ == "__main__":
    unittest.main()
